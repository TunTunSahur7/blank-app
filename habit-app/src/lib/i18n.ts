const DICTS: Record<Lang, Strings> = { en, sq };

let current: Lang = 'en';

/** Called by the store when the language setting loads or changes. */
export function setLanguage(lang: Lang) {
  current = lang;
}

export function getLanguage(): Lang {
  return current;
}

/** Strings for code outside React (notifications, widget data). Components use useStrings(). */
export function strings(lang: Lang = current): Strings {
  return DICTS[lang];
}

export function formatLongDate(d: Date, s: Strings = strings()): string {
  return s.longDate(s.weekdays[d.getDay()], d.getDate(), s.months[d.getMonth()]);
}

export function formatTime(hhmm: string, s: Strings = strings()): string {
  const [h, m] = hhmm.split(':').map(Number);
  const mm = String(m).padStart(2, '0');
  if (s.use24h) return `${String(h).padStart(2, '0')}:${mm}`;
  return `${h % 12 === 0 ? 12 : h % 12}:${mm} ${h < 12 ? 'AM' : 'PM'}`;
}
